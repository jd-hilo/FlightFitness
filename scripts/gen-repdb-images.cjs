/**
 * Generate lib/repdbImages.ts — explicit require() map for RepDB flat WebPs.
 * Metro cannot resolve dynamic require paths.
 *
 *   node scripts/gen-repdb-images.cjs
 */

const { readdirSync, writeFileSync, existsSync } = require('node:fs');
const { join } = require('node:path');

const ROOT = join(__dirname, '..');
const DIR = 'assets/repdb/images/flat';
const OUT = join(ROOT, 'lib/repdbImages.ts');

if (!existsSync(join(ROOT, DIR))) {
  console.error(`Missing ${DIR}. Sync RepDB free bundle first.`);
  process.exit(1);
}

const files = readdirSync(join(ROOT, DIR))
  .filter((f) => f.endsWith('.webp'))
  .sort();

const body = files
  .map((f) => `  '${f.replace(/\.webp$/, '')}': require('../${DIR}/${f}'),`)
  .join('\n');

const out = `// Auto-generated by scripts/gen-repdb-images.cjs — do not edit by hand.
// Run \`npm run gen:repdb-images\` after syncing assets/repdb.

export type RepdbImageVariant = 'start' | 'peak' | 'main';

/** filename without .webp → Metro module id */
export const REPDB_FLAT_IMAGES: Record<string, number> = {
${body}
};

export function getRepdbFlatImage(
  slug: string,
  variant: RepdbImageVariant
): number | undefined {
  return REPDB_FLAT_IMAGES[\`\${slug}-\${variant}\`];
}
`;

writeFileSync(OUT, out);
console.log(`Generated ${files.length} flat images → lib/repdbImages.ts`);
